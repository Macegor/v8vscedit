/**
 * Безопасная попытка загрузить production-модуль, которого на момент запуска
 * тестов может ещё не существовать (фаза «красный» TDD — тесты пишутся ДО
 * реализации `infra/xml/childObjects/ChildObjectsOrder.ts` и
 * `ChildObjectsEditor.ts`).
 *
 * ПОЧЕМУ не статический `import`: раннер (`src/test/suite/index.ts`) грузит
 * ВСЕ скомпилированные `**\/*.test.js` через `require()` в цикле по глобу перед
 * тем, как Mocha начинает регистрировать/фильтровать тесты. Статический
 * `import` несуществующего модуля транспилируется в `require(...)` на верхнем
 * уровне файла и бросает `MODULE_NOT_FOUND` СИНХРОННО в момент загрузки —
 * необработанное исключение в этом цикле обрывает загрузку ВСЕХ ОСТАЛЬНЫХ
 * файлов из глоба (`MOCHA_GREP` фильтрует уже ЗАРЕГИСТРИРОВАННЫЕ тесты и здесь
 * не спасает — до регистрации дело просто не доходит).
 *
 * Поэтому загрузка модуля вызывается ЛЕНИВО (внутри вызова этой функции, а не
 * на верхнем уровне вызывающего файла) и обёрнута в try/catch: при отсутствии
 * модуля возвращается `undefined`, и конкретный тест, которому он нужен,
 * проваливается ОСМЫСЛЕННЫМ `assert.fail(...)` с объяснением — вместо того,
 * чтобы обрушить загрузку всего прогона.
 *
 * `require` (а не динамический `import()`) выбран намеренно: динамический
 * `import('литеральный/путь')` заставляет `tsc` пытаться статически
 * разрешить модуль ДЛЯ ТИПОВ (диагностика `TS2307`, ненулевой код возврата
 * `tsc`), тогда как `require(строка)` типизирован в `@types/node` как
 * `(id: string) => any` и НЕ проверяется резолвером модулей на этапе
 * компиляции — компиляция остаётся чистой (0 диагностик) до тех пор, пока
 * реализация не появится, а фактическая проверка происходит в рантайме теста.
 *
 * @param relativePathFromThisFile Путь к модулю ОТНОСИТЕЛЬНО ЭТОГО файла
 *   (`support/tryRequireProductionModule.ts`), не относительно вызывающего
 *   теста — `require()` резолвит путь по файлу, где он ФИЗИЧЕСКИ записан.
 *   Пример: из `src/test/suite/*.test.ts` модуль `src/infra/xml/childObjects/X.ts`
 *   передаётся как `'../../../infra/xml/childObjects/X'` (3 уровня вверх от
 *   `support/` до `src/`, как и в `typedFieldCorpus.ts`).
 * @returns Загруженный модуль (`unknown` — вызывающий сам приводит к
 *   ожидаемой форме через `as`; дженерик здесь не нужен, тип параметра
 *   использовался бы только один раз — в возврате).
 */
export function tryRequireProductionModule(relativePathFromThisFile: string): unknown {
  try {
    return require(relativePathFromThisFile) as unknown;
  } catch (err) {
    const code = err instanceof Error ? (err as NodeJS.ErrnoException).code : undefined;
    if (code === 'MODULE_NOT_FOUND') {
      return undefined;
    }
    throw err;
  }
}
