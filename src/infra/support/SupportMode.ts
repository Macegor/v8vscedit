/**
 * Режим поддержки объекта метаданных 1С по `ParentConfigurations.bin`.
 * Вынесен в отдельный модуль, чтобы парсер и сервис не образовывали
 * циклический импорт (таблица кодов парсера читает enum на верхнем уровне модуля).
 *
 * Строковые значения, а не коды файла: код режима — деталь формата bin (её знает
 * только парсер), а строка без перевода уходит в протокол webview.
 */
export const enum SupportMode {
  /** Записи нет: собственный объект или у конфигурации нет данных поддержки. */
  None = 'none',
  /** Код 0: на поддержке, редактирование запрещено. */
  Locked = 'locked',
  /** Код 1: на поддержке, редактирование разрешено с сохранением поддержки. */
  Editable = 'editable',
  /** Код 2: снят с поддержки, ограничений нет. */
  Removed = 'removed',
}
